    private void jButton11ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton11ActionPerformed
        // TODO add your handling code here:
        try {
            
            if(keyFlag==2) {
                if(txtEmpID.getText().length()>=6) {
                    try {
                        manualAttendance();
                        windowSettingsClose();
                    } catch (ParseException ex) {
                        Logger.getLogger(SettingsWindow.class.getName()).log(Level.SEVERE, null, ex);
                    }
                }
            } else if(numDisplay1.getText().length()>0) {
                    
                    if(validateLogin()) {
                        numDisplay1.setEditable(false);
                        txtEmpID.setEditable(true);
                        jButton11.setText("OK");
                        jTabbedPane1.show();
                        displayUpdateInfo();
                        jPanel3.hide();
                        keyFlag = 2;
                    } else {
                        MainGUI.infoBox("Pass Keys does not match!", "Error");
                        numDisplay1.setText("");
                        numDisplay.setText("");
                        numDisplay1.setEditable(false);
                        numDisplay.setEditable(true);
                        keyFlag = 0;
                    }
            } else if(numDisplay.getText().length()>0) {
                numDisplay.setEditable(false);
                numDisplay1.setEditable(true);
                keyFlag = 1;
            } else if(numDisplay1.getText().length()>0)
                MainGUI.infoBox("Please Enter KEY#2.","Warning!");
                else
                    MainGUI.infoBox("Please Enter KEY#1.","Warning!");
            
        } catch (SQLException ex) {
            Logger.getLogger(SettingsWindow.class.getName()).log(Level.SEVERE, null, ex);
         }
    }//GEN-LAST:event_jButton11ActionPerformed

