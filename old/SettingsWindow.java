    boolean  validateLogin() throws SQLException {
        DigitalPersona dp = new DigitalPersona();
        String sql = "Select * from tbl_masteraccount WHERE emp_id='"+numDisplay.getText()+
                "' AND masterpass='"+numDisplay1.getText()+"'";
        
        PreparedStatement st = dp.cn().prepareStatement(sql);
        ResultSet rs = st.executeQuery();
       
        return rs.next();
    }
    
    public void manualAttendance() throws SQLException, ParseException {
        DigitalPersona dp = new DigitalPersona();
        PreparedStatement st = dp.cn().prepareStatement("SELECT firstname,lastname,department,position_title FROM tbl_employee INNER JOIN tbl_position INNER JOIN tbl_department "+
                    " ON `tbl_employee`.`position_id` = `tbl_position`.`position_id` AND `tbl_employee`.`department_id` = `tbl_department`.`department_id`" +
                    " WHERE `tbl_employee`.`emp_id` = '"+txtEmpID.getText()+"'");
        ResultSet rs = st.executeQuery();
        Crud c = new Crud();
        
        while (rs.next()) {
            String n = rs.getString("lastname")+", "+rs.getString("firstname");
            c.newAttendance(txtEmpID.getText(),n,rs.getString("position_title"),rs.getString("department"));
        }
    }
    
    public void displayUpdateInfo() {
    
        BufferedReader br = null; 
		
		try {
                    
                    File indexDir = new File("C:\\index"); //default index file save location
			
                    for (final File filename : indexDir.listFiles()) {
			
                        br = new BufferedReader(new FileReader(filename)); //read JSON format array in the index file
                        String thisLine = br.readLine();
                        
                        JSONObject jo = new JSONObject(thisLine);
                        
                        jTextArea1.setText(jo.getString("Date"));
                        jLabel7.setText(jo.getInt("Count")+"");
                    }
		} catch (IOException e) {
			e.printStackTrace();
		} finally {
                    try {
			if (br != null)br.close();
                    } catch (IOException ex) {
                        ex.printStackTrace();
                    }
		}
    }
    
